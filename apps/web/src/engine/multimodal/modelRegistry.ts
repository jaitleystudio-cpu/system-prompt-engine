/**
 * Computes individual file SHA-256 digest.
 */
export function computeFileSha256(bytes: Uint8Array): FileSha256 {
  return computeSha256(bytes);
}

/**
 * Computes canonical payload SHA-256 digest from actual concatenated file bytes.
 * Files are concatenated deterministically in lexicographical order of their filenames.
 */
export function computePayloadSha256(files: Record<string, Uint8Array>): PayloadSha256 {
  const sortedNames = Object.keys(files).sort();
  let totalLength = 0;
  for (const name of sortedNames) {
    totalLength += files[name].length;
  }
  const combined = new Uint8Array(totalLength);
  let offset = 0;
  for (const name of sortedNames) {
    combined.set(files[name], offset);
    offset += files[name].length;
  }
  return computeSha256(combined);
}

/**
 * Computes canonical manifest digest over serialized deterministic metadata.
 * Strips volatile/derived digest fields to avoid circularity.
 */
export function computeManifestDigest(manifest: ModelManifest | CanonicalProductionModel): ManifestDigest {
  const normalized = {
    modelId: manifest.modelId,
    version: manifest.version,
    source: (manifest as ModelManifest).source || (manifest as CanonicalProductionModel).upstreamRepository,
    license: manifest.license,
    expectedSizeBytes: (manifest as ModelManifest).expectedSizeBytes ?? (manifest as CanonicalProductionModel).totalSizeBytes,
    files: [...manifest.files]
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((f) => ({
        name: f.name,
        sizeBytes: (f as any).sizeBytes ?? (f as any).expectedSizeBytes,
        sha256: (f as any).sha256 ?? (f as any).expectedSha256,
        required: f.required,
      })),
    supportedLanguages: [...manifest.supportedLanguages].sort(),
    supportedRuntimes: [...manifest.supportedRuntimes].sort(),
  };
  return computeSha256(JSON.stringify(normalized));
}

/**
 * Computes SHA-256 over entire .spemodel archive buffer.
 */
export function computeArchiveSha256(archiveBytes: Uint8Array): ArchiveSha256 {
  return computeSha256(archiveBytes);
}

/**
 * Anti-fraud check: Ensures a claimed payload digest was not generated by hashing
 * an array of hex hash strings instead of physical binary bytes.
 */
export function verifyPayloadDigestSemantic(
  claimedPayloadSha: string,
  filesPayload: Record<string, Uint8Array>,
): void {
  const sortedNames = Object.keys(filesPayload).sort();
  const fileHashes = sortedNames.map((n) => computeSha256(filesPayload[n]));
  const stringDerived = computeSha256(fileHashes.join(":"));
  if (claimedPayloadSha.toLowerCase() === stringDerived.toLowerCase()) {
    throw new Error(
      "DIGEST_SEMANTIC_VIOLATION: Hash of file-hash strings cannot be mislabeled as payload hash",
    );
  }
}

/**
 * Disambiguates manifest metadata digest from physical artifact / payload SHA.
 */
export function verifyDigestSemanticDisambiguation(
  manifest: ModelManifest,
  claimedArtifactSha: string,
): void {
  const mDigest = manifest.manifestDigest || manifest.sha256;
  if (claimedArtifactSha.toLowerCase() === mDigest.toLowerCase()) {
    throw new Error(
      "DIGEST_SEMANTIC_VIOLATION: Manifest metadata digest cannot be mislabeled as model artifact SHA",
    );
  }
}

/**
 * Asserts that verifiedDigest is computed from real file bytes, not string labels or manifest copies.
 */
export function assertVerifiedDigestComputedFromBytes(
  verifiedDigest: string,
  filesPayload: Record<string, Uint8Array>,
): void {
  const actualPayloadSha = computePayloadSha256(filesPayload);
  if (verifiedDigest.toLowerCase() !== actualPayloadSha.toLowerCase()) {
    throw new Error(
      `DIGEST_INTEGRITY_VIOLATION: verifiedDigest '${verifiedDigest}' does not match computed payload hash '${actualPayloadSha}' over provided bytes`,
    );
  }
}

