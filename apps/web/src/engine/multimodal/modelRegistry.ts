export function deriveLanguagesFromRecognizer(recognizerId: string): string[] {
  const cap = RECOGNIZER_CAPABILITIES[recognizerId];
  if (!cap) {
    throw new Error(
      `UNKNOWN_RECOGNIZER_CAPABILITY: No registered capability for recognizer '${recognizerId}'`,
    );
  }
  return [...cap.supportedLanguages];
}

