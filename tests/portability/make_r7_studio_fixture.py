#!/usr/bin/env python3
"""CI fixture bridge: real Chromium R0 observation -> canonical .spe -> Studio.

No model called; source artifacts are generated by the existing .spe serializer.
This script is test support, not an engine, release authority, or provider.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from spe_runtime.portability.browser_recovery_lineage import (
    attach_recovery_to_spe, dump_attached_spe,
)
from spe_runtime.portability.spe_artifact import (
    build_spe_artifact, verify_integrity,
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence-dir", type=Path, required=True)
    parser.add_argument("--output-spe", type=Path, required=True)
    args = parser.parse_args()
    manifest = json.loads(
        (args.evidence_dir / "living-spe-recovery.json").read_text(encoding="utf-8")
    )
    goal = manifest["protectedGoal"]
    # R0's deterministic fixture uses the exact goal as its compiled prompt;
    # do not invent a compiler or rewrite ProtectedIntent for the fixture.
    source = build_spe_artifact({
        "created_at_utc": "2026-10-18T00:00:00Z",
        "user_request": goal,
        "category": "CODING",
        "target": "general",
        "envelope": {"fixture_scope": "R7_STUDIO_CROSS_RUNTIME_ONLY"},
        "rendered_prompt": goal,
        "intent": {
            "goal": goal,
            "hard_constraints": [{"statement": "Preserve the canvas and action"}],
            "authority_state": {"status": "NONE", "level": 0, "grants": []},
        },
        "lineage": {"not_a_release": True, "origin": "R0_CHROMIUM_FIXTURE"},
    })
    attached = attach_recovery_to_spe(source, manifest, args.evidence_dir)
    assert verify_integrity(attached)["integrity"]["state"] == "VERIFIED"
    assert attached["execution_record"]["execution_authority"] == "NONE"
    assert attached["execution_record"]["repair_trace"]["prompt_v2_text"] == manifest["repair"]["prompt"]
    raw = dump_attached_spe(attached)
    assert len(raw.encode("utf-8")) < 256_000
    args.output_spe.parent.mkdir(parents=True, exist_ok=True)
    args.output_spe.write_text(raw, encoding="utf-8")
    print("PASS R7: existing Python .spe serializer preserved bounded Prompt V2 trace")
    print("PROOF_SCOPE: REAL_BROWSER_DETERMINISTIC_FIXTURE_NO_LIVE_AI")


if __name__ == "__main__":
    main()
